def unit(title, start, end, paragraphs, takeaways, *, kind='concept', quiz=None, **extras):
    if quiz:
        extras['question'] = question(*quiz)
    result = section(title, list(range(start, end + 1)), paragraphs, takeaways, **extras)
    result['kind'] = kind
    return result


def figure(title, caption, *nodes):
    return dict(title=title, caption=caption, steps=[dict(label=label, detail=detail) for label, detail in nodes])


def table(headers, *rows):
    return dict(headers=headers, rows=rows)


