def fig(title, caption, *steps):
    return dict(title=title, steps=[dict(label=a, detail=b) for a, b in steps], caption=caption)


def unit(title, first, last, paragraphs, takeaway, quiz=None, kind="concept", **extra):
    if quiz:
        extra["question"] = question(*quiz)
    item = section(title, range(first, last + 1), paragraphs, [takeaway], **extra)
    item["kind"] = kind
    return item


